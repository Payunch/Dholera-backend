async function seedPremiumBlogs() {
  try {
    console.log('Seeding premium blogs...');
    for (const article of articles) {
      const [record, created] = await Update.findOrCreate({
        where: { id: article.id },
        defaults: article
      });

      if (!created) {
        await record.update(article);
        console.log(`Updated blog ID ${article.id}: "${article.title}"`);
      } else {
        console.log(`Created blog ID ${article.id}: "${article.title}"`);
      }
    }
    console.log('Database seeding successfully completed.');
    process.exit(0);
  } catch (error) {
    console.error('Error seeding premium blogs:', error);
    process.exit(1);
  }
}

