async function run() {
  await sequelize.sync();
  
  // Get all English posts (published + unpublished)
  const allPosts = await Update.findAll({
    where: { lang: 'en' },
    order: [['id', 'ASC']]
  });
  
  console.log(`\nFound ${allPosts.length} English posts total.\n`);
  
  let translatedCount = 0;
  let publishedCount = 0;
  
  for (const post of allPosts) {
    const trans = TRANSLATIONS[post.id];
    if (!trans) {
      console.log(`  ID:${post.id} — No translation mapping found, skipping.`);
      continue;
    }
    
    const updateData = {};
    let needsUpdate = false;
    
    // Add translations if missing
    if (!post.title_hi || !post.content_hi) {
      updateData.title_hi = trans.title_hi;
      updateData.content_hi = getHindiContent(post.id, post.content);
      needsUpdate = true;
      console.log(`  ID:${post.id} — Adding Hindi translation`);
    }
    
    if (!post.title_gu || !post.content_gu) {
      updateData.title_gu = trans.title_gu;
      updateData.content_gu = getGujaratiContent(post.id, post.content);
      needsUpdate = true;
      console.log(`  ID:${post.id} — Adding Gujarati translation`);
    }
    
    // Publish drafts if not already published
    if (!post.published || !post.isApproved) {
      updateData.published = true;
      updateData.isApproved = true;
      publishedCount++;
      console.log(`  ID:${post.id} — Publishing draft`);
      needsUpdate = true;
    }
    
    if (needsUpdate) {
      await post.update(updateData);
      translatedCount++;
      console.log(`  ID:${post.id} ✓ Updated: "${post.title}"`);
    } else {
      console.log(`  ID:${post.id} — Already has translations, no changes needed.`);
    }
  }
  
  console.log(`\n=== DONE ===`);
  console.log(`Translated: ${translatedCount} posts`);
  console.log(`Published: ${publishedCount} drafts`);
  
  process.exit();
}

run().catch(err => { console.error('FATAL:', err); process.exit(1); });
